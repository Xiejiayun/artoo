    private func waitForLiveConnection() throws {
        let connected = app.descendants(matching: .any).matching(identifier: "realtimeStatus").matching(NSPredicate(format: "value == %@", "connected")).firstMatch
        try require(connected.waitForExistence(timeout: 20), "The phone must connect its authenticated WebSocket")
    }
    @MainActor
    private func reveal(_ element: XCUIElement) throws {
        for attempt in 0..<14 {
            if element.exists && element.isHittable { return }
            // App-wide swipes can begin on the keyboard after a form grows.
            // Keep both drag points in the visible native content instead.
            let bounds = app.frame
            let list = app.collectionViews.firstMatch
            let rect = list.exists ? list.frame.intersection(bounds) : bounds
            let navigation = app.navigationBars.firstMatch
            let tabs = app.tabBars.firstMatch
            let keyboard = app.keyboards.firstMatch
            let top = navigation.exists ? max(rect.minY, navigation.frame.maxY) : rect.minY
            var bottom = tabs.exists ? min(rect.maxY, tabs.frame.minY) : rect.maxY
            if keyboard.exists { bottom = min(bottom, keyboard.frame.minY) }
            let viewport = CGRect(x: rect.minX + 6, y: top + 8,
                                  width: rect.width - 12, height: bottom - top - 16)
            try require([viewport.minX, viewport.minY, viewport.width, viewport.height].allSatisfy { $0.isFinite }
                        && !viewport.isEmpty && bounds.contains(viewport),
                        "Control scrolling must stay inside finite content bounds above the keyboard")
            let frame = element.exists ? element.frame : .zero
            let known = !frame.isEmpty && [frame.minX, frame.minY, frame.width, frame.height].allSatisfy { $0.isFinite }
            let upward = known ? frame.midY > viewport.midY : attempt < 7
            let origin = app.coordinate(withNormalizedOffset: .zero)
            origin.withOffset(CGVector(dx: viewport.midX, dy: viewport.minY + viewport.height * (upward ? 0.7 : 0.3)))
                .press(forDuration: 0.05, thenDragTo: origin.withOffset(CGVector(dx: viewport.midX, dy: viewport.minY + viewport.height * (upward ? 0.3 : 0.7))))
        }
        try require(element.exists && element.isHittable, "The requested native control must be reachable")
    }

    @MainActor
    private func viewport() throws -> CGRect {
        let list = app.collectionViews.firstMatch
        try require(list.exists && !app.keyboards.firstMatch.exists, "Evidence must use an unobscured native list")
        let rect = list.frame.intersection(app.frame), nav = app.navigationBars.firstMatch, tabs = app.tabBars.firstMatch
        var top = nav.exists ? max(rect.minY, nav.frame.maxY) : rect.minY
        var bottom = tabs.exists ? min(rect.maxY, tabs.frame.minY) : rect.maxY
        let connection = field("realtimeStatus"), composer = field("conversation.composer")
        if connection.exists && !connection.frame.isEmpty { top = max(top, connection.frame.maxY + 4) }
        if composer.exists && !composer.frame.isEmpty { bottom = min(bottom, composer.frame.minY - 4) }
        let visible = CGRect(x: rect.minX + 2, y: top + 2, width: rect.width - 4, height: bottom - top - 4)
        try require(!visible.isEmpty && !visible.isNull && !visible.isInfinite, "The content viewport must have a real visible frame")
        return visible
    }
    @MainActor
    private func drag(_ view: CGRect, upward: Bool) {
        let origin = app.coordinate(withNormalizedOffset: .zero)
        origin.withOffset(CGVector(dx: view.midX, dy: view.minY + view.height * (upward ? 0.7 : 0.3)))
            .press(forDuration: 0.05, thenDragTo: origin.withOffset(CGVector(dx: view.midX, dy: view.minY + view.height * (upward ? 0.3 : 0.7))))
    }
    @MainActor
    private func revealText(_ element: XCUIElement) throws {
        for attempt in 0..<24 {
            let view = try viewport(); var upward = attempt < 12
            if element.exists {
                let rect = element.frame
                if !rect.isEmpty && !rect.isNull && !rect.isInfinite {
                    let visible = rect.intersection(view)
                    let requiredHeight = rect.height <= view.height ? rect.height : view.height / 2
                    if !visible.isNull && visible.width >= rect.width - 1 && visible.height >= requiredHeight - 1 { return }
                    upward = rect.midY > view.midY
                }
            }
            drag(view, upward: upward)
        }
        try require(false, "The exact read-only text must be visibly rendered")
    }
    @MainActor
    private func revealTogether(_ first: XCUIElement, _ second: XCUIElement, selectable: Bool, firstIsComposer: Bool = false) throws {
        for attempt in 0..<18 {
            let view = try viewport(); var upward = attempt < 9
            let firstView = firstIsComposer ? try composerEditingViewport(keyboardRequired: false) : view
            if first.exists && second.exists {
                let frames = [first.frame, second.frame]
                if frames.allSatisfy({ !$0.isEmpty && !$0.isNull && !$0.isInfinite }) {
                    if firstView.contains(frames[0]) && view.contains(frames[1]) &&
                        (selectable || (first.isHittable && second.isHittable)) { return }
                    // Only timeline evidence moves when the list scrolls.
                    let scrollTarget = firstIsComposer ? frames[1] : frames[0].union(frames[1])
                    upward = scrollTarget.midY > view.midY
                }
            }
            drag(view, upward: upward)
        }
        try require(false, "Both pieces of visual evidence must be visible together")
    }
    @MainActor
    private func screenshot(_ name: String) throws {
        for id in ["serverURL", "pairingDeviceName", "pairingCode", "device.pairing.code"] {
            try require(!app.descendants(matching: .any).matching(identifier: id).firstMatch.exists, "Approved screenshots must exclude pairing fields and generated codes")
        }
        let image = XCTAttachment(screenshot: app.screenshot()); image.name = name; image.lifetime = .keepAlways; add(image)
    }
    @MainActor
    private func require(_ condition: Bool, _ message: String) throws {
        if !condition {
            let credentialsVisible = ["serverURL", "pairingDeviceName", "pairingCode", "device.pairing.code"].contains {
                app.descendants(matching: .any).matching(identifier: $0).firstMatch.exists
            }
            if !credentialsVisible {
                let image = XCTAttachment(screenshot: app.screenshot()); image.name = "Native assistant guarded failure diagnostics"; image.lifetime = .keepAlways; add(image)
                let tree = XCTAttachment(string: app.debugDescription); tree.name = "Native assistant failure accessibility hierarchy"; tree.lifetime = .keepAlways; add(tree)
            }
        }
        try demand(condition, message)
    }

    private func turns() async throws -> [AssistantTurnRecord] { let page: AssistantTurnPage = try await get("api/v1/rooms/\(fixture.channelId)/assistant-turns"); return page.turns }
    private func messages() async throws -> [AssistantMessage] { let page: AssistantMessagePage = try await get("api/v1/rooms/\(fixture.channelId)/messages?limit=100"); return page.messages }
    private func waitForTurn(_ body: String, status: String, timeout: TimeInterval = 30, retryingRunId: String? = nil) async throws -> AssistantTurnRecord {
        let deadline = Date().addingTimeInterval(timeout)
        repeat {
            let matching = try await messages().filter { $0.kind == "text" && $0.body == body }
            try demand(matching.count <= 1, "A native request must persist exactly once")
            if let request = matching.first {
                try demand(request.actorType == "user" && request.actorId == fixture.userId && request.threadRootId == nil,
                           "The request must belong to the actual native user in this top-level conversation")
                let candidates = try await turns().filter { $0.userMessageId == request.id }
                try demand(candidates.count <= 1, "A native message must create only one logical turn")
                if let turn = candidates.first {
                    try demand(request.payload?.assistantTurnId == turn.id && turn.roomId == fixture.channelId && turn.threadRootId == nil,
                               "The request and actual turn must retain the same conversation identities")
                    if turn.status == status { return turn }
                    let awaitingRetry = status == "completed" && turn.status == "failed" && retryingRunId != nil && turn.runId == retryingRunId
                    if ["failed", "cancelled"].contains(turn.status) && turn.status != status && !awaitingRetry { throw assistantError("Assistant turn ended unexpectedly as \(turn.status)") }
                }
            }
            try await Task.sleep(nanoseconds: 250_000_000)
        } while Date() < deadline
        throw assistantError("The actual assistant turn did not reach \(status)")
    }
    private func verifiedRun(_ turn: AssistantTurnRecord) async throws -> AssistantRun {
        let id = try XCTUnwrap(turn.runId), envelope: AssistantRunEnvelope = try await get("api/v1/runs/\(id)")
        let run = envelope.run
        try demand(run.id == id && run.taskId == turn.taskId && run.computerId == fixture.computerId
                   && run.agentInstanceId == fixture.instanceId && run.runtimeId == fixture.runtime,
                   "The run must use the exact manually selected original agent, computer and runtime")
        return run
    }
    private func answer(_ turn: AssistantTurnRecord) async throws -> AssistantMessage {
        let id = try XCTUnwrap(turn.responseMessageId), rows = try await messages().filter { $0.id == id }
        try demand(rows.count == 1, "A completed turn must have exactly one persisted answer")
        let answer = rows[0]
        try demand(answer.actorType == "agent" && answer.actorId == fixture.instanceId && answer.threadRootId == nil && answer.payload?.assistantTurnId == turn.id,
                   "The answer must be attributed to the selected instance and exact turn")
        return answer
    }
    private func observations() async throws -> AssistantObservations {
        let deadline = Date().addingTimeInterval(20)
        repeat {
            let snapshot: AssistantObservations = try await request(URLRequest(url: fixture.controlURL.appendingPathComponent("observations")), token: fixture.controlToken)
            if snapshot.incompleteReceipts.isEmpty { return snapshot }
            try await Task.sleep(nanoseconds: 150_000_000)
        } while Date() < deadline
        throw assistantError("An owned startup receipt did not finish writing within the observation deadline")
    }
    private func controlNode(_ action: String) async throws {
        try demand(["start", "stop"].contains(action), "Fixture control only starts or stops the real node")
        let value: AssistantNodeResponse = try await request(URLRequest(url: fixture.controlURL.appendingPathComponent("node/\(action)")),
                                                            token: fixture.controlToken, body: [:], timeout: 75)
        try demand(value.daemon.computerId == fixture.computerId && value.daemon.status == (action == "start" ? "online" : "offline")
                   && value.daemon.connected == (action == "start"), "Node control must observe actual authenticated presence")
    }
    private func waitForHeldProcess(_ turn: AssistantTurnRecord) async throws -> AssistantProcessReceipt {
        let deadline = Date().addingTimeInterval(20)
        repeat {
            let snapshot = try await observations(), matches = snapshot.receipts.filter { $0.runId == turn.runId && $0.turnId == turn.id }
            try demand(matches.count <= 1, "The held run must have only one startup receipt")
            if let receipt = matches.first, snapshot.livePids.contains(receipt.pid) {
                try demand(receipt.mode == "hold" && receipt.taskId == turn.taskId && receipt.pid > 1 && snapshot.receipts.count == 4,
                           "The fourth launch must be the actual held process")
                return receipt
            }
            try await Task.sleep(nanoseconds: 150_000_000)
        } while Date() < deadline
        throw assistantError("The real held subprocess was never observed alive")
    }
    private func waitForNoLiveProcesses() async throws {
        let deadline = Date().addingTimeInterval(30)
        repeat {
            if try await observations().livePids.isEmpty { return }
            try await Task.sleep(nanoseconds: 150_000_000)
        } while Date() < deadline
        throw assistantError("UI cancellation did not terminate the held subprocess")
    }
    private func stable(_ expected: AssistantTurnRecord, status: String, launches: Int, duration: TimeInterval) async throws -> Int {
        let start = Date()
        repeat {
            let current = try await turns().filter { $0.id == expected.id }
            try demand(current.count == 1 && current[0].status == status && current[0].runId == expected.runId
                       && current[0].userMessageId == expected.userMessageId && current[0].responseMessageId == nil,
                       "The terminal request must keep its same identities until the explicit next action")
            let observed = try await observations()
            try demand(observed.receipts.count == launches && observed.livePids.isEmpty, "A terminal turn must not dispatch or leave a process running")
            try await Task.sleep(nanoseconds: 250_000_000)
        } while Date().timeIntervalSince(start) < duration
        return Int(Date().timeIntervalSince(start) * 1000)
    }
    private func get<T: Decodable>(_ path: String) async throws -> T {
        try await request(URLRequest(url: try XCTUnwrap(URL(string: path, relativeTo: fixture.serverURL.appendingPathComponent("/"))).absoluteURL))
    }
    private func request<T: Decodable>(_ initial: URLRequest, token: String? = nil, body: [String: String]? = nil, timeout: TimeInterval = 20) async throws -> T {
        var request = initial; request.timeoutInterval = timeout
        request.setValue("Bearer \(token ?? fixture.peerToken)", forHTTPHeaderField: "Authorization")
        if let body {
            request.httpMethod = "POST"; request.setValue("application/json", forHTTPHeaderField: "Content-Type")
            request.setValue(UUID().uuidString, forHTTPHeaderField: "Idempotency-Key"); request.httpBody = try JSONSerialization.data(withJSONObject: body)
        }
        let config = URLSessionConfiguration.ephemeral; config.httpShouldSetCookies = false
        let session = URLSession(configuration: config); defer { session.invalidateAndCancel() }
        let (data, response) = try await session.data(for: request), http = try XCTUnwrap(response as? HTTPURLResponse)
        try demand((200..<300).contains(http.statusCode), "Authenticated assistant observation failed with HTTP \(http.statusCode)")
        let decoder = JSONDecoder(); decoder.keyDecodingStrategy = .convertFromSnakeCase
        return try decoder.decode(T.self, from: data)
    }
