import XCTest

/// One independent assistant suite. API calls observe outcomes or mint the
/// disposable pairing code; every conversation action uses the native UI.
final class AssistantConversationUITests: XCTestCase {
    private let app = XCUIApplication()
    private var fixture: AssistantFixture!

    override func setUpWithError() throws {
        continueAfterFailure = false
        fixture = try AssistantFixture(ProcessInfo.processInfo.environment)
    }
    override func tearDownWithError() throws { app.terminate() }

    @MainActor
    func testDirectAgentConversationAndRecovery() async throws {
        try await pair()
        try openChannel()
        try waitForLiveConnection()
        try demand(try await turns().isEmpty, "The assistant suite must begin without any precreated turn")
        try demand(try await messages().isEmpty, "The direct conversation must begin empty")
        try selectAgent()
        try await controlNode("stop")
        let firstMessageId = try await send(fixture.firstRequest)
        let firstWaiting = try await waitForTurn(fixture.firstRequest, status: "waiting")
        try demand(firstWaiting.userMessageId == firstMessageId, "The waiting turn must reference the exact native message that was visibly sent")
        try demand(firstWaiting.runId == nil && firstWaiting.responseMessageId == nil, "Offline waiting must not create a run or answer")
        let waitingTask: AssistantTaskEnvelope = try await get("api/v1/tasks/\(firstWaiting.taskId)")
        let waitingObservation = try await observations()
        try demand(waitingTask.runs.isEmpty && waitingObservation.receipts.isEmpty, "No subprocess may start while the selected computer is offline")
        try status(firstWaiting.id, "Waiting")

        let composer = field("messageComposer")
        try replace(composer, fixture.draft)
        try dismissKeyboard()
        app.terminate(); app.launch()
        try require(app.tabBars.buttons["Channels"].waitForExistence(timeout: 20), "Relaunch must restore the authenticated phone")
        try openChannel(); try waitForLiveConnection()
        try status(firstWaiting.id, "Waiting")
        try reveal(composer)
        try require(composer.value as? String == fixture.draft, "Relaunch must restore the unsent assistant draft exactly")
        try assertSelectedAgent()
        let restored = try await waitForTurn(fixture.firstRequest, status: "waiting")
        try demand(restored.id == firstWaiting.id && restored.userMessageId == firstWaiting.userMessageId && restored.runId == nil,
                   "Relaunch must preserve the same waiting logical request without resubmission")
        try revealTogether(composer, app.staticTexts["conversation.turn.status.\(firstWaiting.id)"], selectable: false, firstIsComposer: true)
        try screenshot("Native assistant waiting with draft restored")

        // Reconnection resumes waiting work automatically; no Retry is tapped.
        try await controlNode("start")
        let first = try await waitForTurn(fixture.firstRequest, status: "completed", timeout: 90)
        try demand(first.id == firstWaiting.id && first.userMessageId == firstWaiting.userMessageId, "Automatic dispatch must retain the original request")
        let firstRun = try await verifiedRun(first)
        try demand(firstRun.status == "completed", "The first process must complete")
        let firstAnswer = try await answer(first)
        try demand(firstAnswer.body.range(of: #"^First answer marker: ASSISTANT_[A-F0-9]{32}$"#, options: .regularExpression) != nil,
                   "The first answer must contain the marker generated by its real subprocess")
        try reveal(composer)
        try require(composer.value as? String == fixture.draft, "An arriving answer must not overwrite the unsent draft")
        try demand((try await observations()).receipts.count == 1, "Automatic recovery must launch exactly one process")

        let secondMessageId = try await send(fixture.secondRequest)
        let failed = try await waitForTurn(fixture.secondRequest, status: "failed", timeout: 90)
        try demand(failed.userMessageId == secondMessageId, "The failed follow-up must reference the exact native message that was visibly sent")
        let failedRun = try await verifiedRun(failed)
        try demand(failedRun.status == "failed" && failed.responseMessageId == nil, "The first follow-up attempt must actually fail without an answer")
        try status(failed.id, "Failed")
        let failedObservedMs = try await stable(failed, status: "failed", launches: 2, duration: 3.1)
        try reveal(app.buttons["conversation.turn.retry.\(failed.id)"])
        try require(!app.buttons["conversation.turn.cancel.\(failed.id)"].exists, "A failed request must offer Retry without a running Cancel action")
        try revealTogether(app.staticTexts["conversation.turn.request.\(failed.id)"], app.buttons["conversation.turn.retry.\(failed.id)"], selectable: false)
        try screenshot("Native assistant failed request before retry")
        let retry = app.buttons["conversation.turn.retry.\(failed.id)"]
        try require(retry.isEnabled && retry.isHittable, "Retry must be a reachable action for this specific failed request")
        retry.tap()
        let second = try await waitForTurn(fixture.secondRequest, status: "completed", timeout: 90, retryingRunId: failed.runId)
        try demand(second.id == failed.id && second.userMessageId == failed.userMessageId && second.runId != failed.runId,
                   "UI Retry must retain turn/message identity and create one distinct run")
        let secondRun = try await verifiedRun(second)
        try demand(secondRun.status == "completed", "The explicit retry must complete")
        let secondAnswer = try await answer(second)
        try demand(secondAnswer.body == "Follow-up used the actual earlier answer: \(firstAnswer.body)",
                   "The retry answer must use the first process's actual persisted answer")
        let firstText = app.staticTexts["message.\(firstAnswer.id)"], secondText = app.staticTexts["message.\(secondAnswer.id)"]
        // Real run events remain between the answers in this feed. Verify and
        // capture each complete answer without requiring both to fit one screen.
        try revealText(firstText)
        try require(firstText.label == firstAnswer.body, "The first answer must render its exact persisted content")
        try screenshot("Native assistant first completed answer")
        try revealText(secondText)
        try require(secondText.label == secondAnswer.body, "The follow-up answer must render its exact persisted content")
        try screenshot("Native assistant follow-up uses the actual first answer")

        let holdMessageId = try await send(fixture.holdRequest)
        let held = try await waitForTurn(fixture.holdRequest, status: "running", timeout: 90)
        try demand(held.userMessageId == holdMessageId, "The held turn must reference the exact native message that was visibly sent")
        let heldReceipt = try await waitForHeldProcess(held)
        let heldRun = try await verifiedRun(held)
        try demand(heldRun.status == "running", "The third turn must own a running process")
        try status(held.id, "Running")
        let taskLink = app.buttons["conversation.turn.task.\(held.id)"]
        try reveal(taskLink); taskLink.tap()
        let taskStatus = app.descendants(matching: .any).matching(identifier: "task.status.\(held.taskId)").firstMatch
        try require(taskStatus.waitForExistence(timeout: 15), "The request's linked execution task must open with its exact ID")
        try reveal(taskStatus)
        try require(taskStatus.value as? String == "running", "The linked task must reflect the actual running execution")
        let runLabel = "Run \(heldRun.id), Running"
        let runLinks = app.buttons.matching(NSPredicate(format: "label == %@", runLabel))
        let runLink = runLinks.firstMatch
        try reveal(runLink)
        try require(runLinks.firstMatch.waitForExistence(timeout: 15) && runLinks.count == 1,
                    "The linked task must offer exactly one running navigation row with this complete run ID")
        try require(runLink.label == runLabel && runLink.isHittable, "The exact running row must be visible before opening its summary")
        runLink.tap()
        try require(app.navigationBars["Run Summary"].waitForExistence(timeout: 15), "The actual held run must open its native summary")
        for value in [heldRun.id, held.taskId, fixture.instanceId, fixture.computerId] {
            let text = app.staticTexts.matching(NSPredicate(format: "label == %@", value)).firstMatch
            try revealText(text)
            try require(text.label == value, "Run Summary must expose exact task, run, computer and selected instance identities")
        }
        try screenshot("Native assistant linked execution task")
        app.navigationBars["Run Summary"].buttons.firstMatch.tap()
        try require(app.navigationBars["Task"].waitForExistence(timeout: 10), "Back must return to the linked task")
        app.navigationBars["Task"].buttons.firstMatch.tap()
        try demand((try await observations()).livePids.contains(heldReceipt.pid), "The held process must still be alive before UI cancellation")
        let cancel = app.buttons["conversation.turn.cancel.\(held.id)"]
        try reveal(cancel)
        try require(cancel.isEnabled && cancel.isHittable, "Cancel must target only the running request")
        cancel.tap()
        let cancelled = try await waitForTurn(fixture.holdRequest, status: "cancelled")
        try demand(cancelled.id == held.id && cancelled.runId == held.runId && cancelled.responseMessageId == nil,
                   "UI cancellation must terminate this same turn/run without creating an answer")
        let cancelledRun = try await verifiedRun(cancelled)
        try demand(cancelledRun.status == "cancelled", "The linked run must also be cancelled")
        try await waitForNoLiveProcesses()
        let cancelledObservedMs = try await stable(cancelled, status: "cancelled", launches: 4, duration: 3.1)
        try status(cancelled.id, "Cancelled")
        try require(!app.buttons["conversation.turn.cancel.\(held.id)"].exists && !app.buttons["conversation.turn.retry.\(held.id)"].exists,
                    "A cancelled request must not keep Retry or Cancel controls")
        try revealTogether(app.staticTexts["conversation.turn.request.\(held.id)"], app.staticTexts["conversation.turn.status.\(held.id)"], selectable: false)
        try screenshot("Native assistant cancelled with process stopped")

        let finalTurns = try await turns(), finalMessages = try await messages(), finalObservation = try await observations()
        try demand(finalTurns.count == 3 && finalObservation.receipts.count == 4 && finalObservation.livePids.isEmpty,
                   "The scenario must retain three turns, four launches and no live process")
        try demand(finalMessages.filter { $0.kind == "text" && $0.actorType == "agent" }.count == 2,
                   "Only the first request and successful follow-up may produce agent answers")
        try demand(!finalMessages.contains { $0.body == fixture.draft }, "The restored draft must never have been sent")
        let receipt = XCTAttachment(data: try JSONSerialization.data(withJSONObject: [
            "first_turn_id": first.id, "followup_turn_id": second.id, "cancelled_turn_id": held.id,
            "first_run_id": firstRun.id, "failed_run_id": failedRun.id, "retry_run_id": secondRun.id, "cancelled_run_id": heldRun.id,
            "held_pid": heldReceipt.pid, "failed_observed_ms": failedObservedMs, "cancelled_observed_ms": cancelledObservedMs,
            "restored_draft_remained_unsent": true, "runtime_scope": "deterministic CLI over production node WebSocket"
        ], options: .sortedKeys), uniformTypeIdentifier: "public.json")
        receipt.name = "Native assistant exact identities and observed lifecycle boundaries"; receipt.lifetime = .keepAlways; add(receipt)
    }

    @MainActor
    private func pair() async throws {
        app.launch()
        let readyOrigin = app.textFields.matching(identifier: "serverURL").matching(NSPredicate(format: "enabled == true")).firstMatch
        let deadline = Date().addingTimeInterval(30)
        while Date() < deadline && !app.tabBars.buttons["More"].exists && !readyOrigin.exists {
            try await Task.sleep(nanoseconds: 100_000_000)
        }
        if app.tabBars.buttons["More"].exists {
            app.tabBars.buttons["More"].tap()
            let signOut = app.buttons["signOut"]; try reveal(signOut); signOut.tap()
        }
        let serverField = readyOrigin
        try require(serverField.waitForExistence(timeout: 30), "Pairing must be available before entering the disposable credentials")
        let code: AssistantPairingCode = try await request(URLRequest(url: fixture.serverURL.appendingPathComponent("api/v1/devices/pairings")),
                                                          body: ["intended_platform": "ios"])
        if fixture.serverURL.scheme == "http" {
            let toggle = app.switches["allowLocalHTTP"]
            for _ in 0..<3 {
                try reveal(toggle)
                if toggle.value as? String == "1" { break }
                try require(toggle.value as? String == "0", "Local HTTP switch must expose a known state")
                let nested = toggle.switches.firstMatch; (nested.exists ? nested : toggle).tap()
                _ = XCTWaiter.wait(for: [XCTNSPredicateExpectation(predicate: NSPredicate(format: "value == %@", "1"), object: toggle)], timeout: 3)
            }
            try require(toggle.value as? String == "1", "Loopback HTTP must be enabled through the real onboarding switch")
        }
        try replace(serverField, fixture.serverURL.absoluteString)
        try replace(app.textFields["pairingDeviceName"], fixture.deviceName)
        try replace(app.textFields["pairingCode"], code.code)
        let pair = app.buttons["pairDevice"]; try reveal(pair); try require(pair.isEnabled, "The completed pairing form must allow connection"); pair.tap()
        try require(app.tabBars.buttons["Channels"].waitForExistence(timeout: 20), "Native UI pairing must authenticate and load the shared server")
    }

