    @MainActor
    private func selectAgent() throws {
        let destination = app.descendants(matching: .any).matching(identifier: "conversation.destination").firstMatch
        try reveal(destination); destination.tap()
        let agent = app.buttons["Agent"]; try require(agent.waitForExistence(timeout: 5), "The destination picker must offer Agent"); agent.tap()
        let picker = app.descendants(matching: .any).matching(identifier: "conversation.agent").firstMatch
        try reveal(picker); picker.tap()
        let selected = try agentOption(fixture.instanceId), collision = try agentOption(fixture.collisionId)
        for (option, id, other) in [(selected, fixture.instanceId, fixture.collisionId), (collision, fixture.collisionId, fixture.instanceId)] {
            try require(option.label.contains(fixture.agentName) && option.label.contains(fixture.computerName)
                        && option.label.contains(fixture.runtime) && option.label.contains("Instance: \(id)") && !option.label.contains(other),
                        "Same-name agent choices must retain readable details and their complete distinct instance IDs")
        }
        try revealTogether(selected, collision, selectable: false)
        try screenshot("Native assistant readable agent selection")
        selected.tap()
        try assertSelectedAgent()
    }

